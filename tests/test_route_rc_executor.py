def test_route_rc_executor_resolves_relative_artifact_paths_from_orchestration_dir(tmp_path: Path) -> None:
    orchestration_json = _write_orchestration(tmp_path / "orchestration" / "route_rc_orchestration.json")
    payload = json.loads(orchestration_json.read_text(encoding="utf-8"))
    payload["steps"][0]["path"] = "rc/route_certification_pack/route_certification_pack.json"
    payload["artifact_index"]["route_certification_pack"] = payload["steps"][0]["path"]
    orchestration_json.write_text(json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True), encoding="utf-8")

    report = RouteReleaseCandidateExecutorService(command_runner=_RecordingRunner()).execute(
        orchestration_json=orchestration_json,
        output_dir=tmp_path / "execution",
    )
    receipt = json.loads(Path(report.json_path).read_text(encoding="utf-8"))

    expected = orchestration_json.parent / "rc" / "route_certification_pack" / "route_certification_pack.json"
    artifacts = {item["name"]: item["path"] for item in receipt["artifacts"]}
    assert receipt["steps"][0]["path"] == str(expected)
    assert artifacts["route_certification_pack"] == str(expected)
