"""Customer-facing trust-center export for the OSS benchmark."""

from __future__ import annotations

import json
from html import escape
from pathlib import Path
from typing import Any

from tools.oss_benchmark.config import (
    DATA_PATH,
    ROOT,
    TRUST_CENTER_BADGE_PATH,
    TRUST_CENTER_DATA_PATH,
    TRUST_CENTER_PATH,
)


def build_trust_center_export(payload: dict[str, Any]) -> dict[str, Any]:
    """Build a customer-ready dpone certification snapshot from merged evidence."""

    dpone = _find_project(payload, "dpone")
    index = dpone.get("industrial_maintainability") or {}
    gates = payload.get("quality_gates") or {}
    freshness = payload.get("freshness_summary") or {}
    score = _as_int(index.get("score"))
    status = _status(score, gates, freshness)
    return {
        "schema_version": 1,
        "title": "dpone Trust Center Snapshot",
        "status": status,
        "summary": (
            "Customer-ready certification snapshot for dpone code quality, governance, security, reliability, "
            "operability, freshness and benchmark evidence."
        ),
        "run_context": payload.get("run_context") or {},
        "badge": {"label": f"dpone {status}", "score": score, "band": index.get("band", "n/a")},
        "quality_gates": gates,
        "freshness": freshness,
        "controls": _controls(payload, dpone),
        "evidence_links": [
            {"label": "Open benchmark report", "href": "oss-code-quality-benchmark-2026-06-12.md"},
            {"label": "Open benchmark evidence", "href": DATA_PATH.relative_to(DATA_PATH.parent.parent).as_posix()},
            {"label": "Open trust-center JSON", "href": f"data/{TRUST_CENTER_DATA_PATH.name}"},
        ],
        "limitations": [
            "Static maintainability and governance proxies, not runtime performance claims.",
            "Closed-core competitors are included only as public-documentation posture comparators.",
            "Fresh/stale semantics are inherited from the merged benchmark evidence payload.",
        ],
    }


def write_trust_center_outputs(payload: dict[str, Any], *, root: Path = ROOT) -> dict[str, Any]:
    """Write the customer-facing Markdown, JSON and badge SVG artifacts."""

    export = payload.get("trust_center") or build_trust_center_export(payload)
    _write_text(root / TRUST_CENTER_DATA_PATH, json.dumps(export, indent=2, sort_keys=True) + "\n")
    _write_text(root / TRUST_CENTER_PATH, render_trust_center_markdown(export))
    _write_text(root / TRUST_CENTER_BADGE_PATH, render_trust_center_badge_svg(export))
    return export


def render_trust_center_markdown(export: dict[str, Any]) -> str:
    run_context = export.get("run_context") or {}
    badge = export.get("badge") or {}
    gates = export.get("quality_gates") or {}
    freshness = export.get("freshness") or {}
    lines = [
        f"# {export.get('title', 'dpone Trust Center Snapshot')}",
        "",
        str(export.get("summary") or "Customer-ready certification snapshot for dpone."),
        "",
        "![dpone trust center badge](assets/dpone-trust-center-badge.svg)",
        "",
        "| Certification metadata | Value |",
        "|---|---|",
        f"| Status | `{export.get('status', 'unknown')}` |",
        f"| Badge | `{badge.get('label', 'dpone unknown')}` / `{badge.get('score', 'n/a')}` |",
        f"| Last refresh | `{run_context.get('generated_at', 'unknown')}` |",
        f"| Generated by | `{run_context.get('updated_by', 'local')}` |",
        f"| Source revision | `{run_context.get('branch', 'local')}@{run_context.get('git_sha', 'unknown')}` |",
        f"| Quality gates | `{gates.get('status', 'unknown')}` ({gates.get('passed', 0)} passed, {gates.get('failed', 0)} failed) |",
        f"| Freshness | fresh `{freshness.get('fresh', 0)}`, stale `{freshness.get('stale', 0)}`, unavailable `{freshness.get('unavailable', 0)}` |",
        "",
        f"Quality gates: `{gates.get('status', 'unknown')}`.",
        "",
        "## Customer-ready certification",
        "",
        "| Control | Score | Band | Evidence |",
        "|---|---:|---|---|",
    ]
    for control in export.get("controls", []):
        lines.append(
            "| "
            f"{control.get('label', control.get('slug', 'control'))} | "
            f"{control.get('score', 'n/a')} | "
            f"{control.get('band', 'n/a')} | "
            f"{control.get('evidence', 'n/a')} |"
        )
    lines.extend(["", "## Evidence links", ""])
    for link in export.get("evidence_links", []):
        lines.append(f"- [{link.get('label', 'evidence')}]({link.get('href', '#')})")
    lines.extend(["", "## Limitations", ""])
    for limitation in export.get("limitations", []):
        lines.append(f"- {limitation}")
    lines.append("")
    return "\n".join(lines)


def render_trust_center_badge_svg(export: dict[str, Any]) -> str:
    badge = export.get("badge") or {}
    score = _as_int(badge.get("score"))
    status = str(export.get("status") or "unknown")
    color = "#0f766e" if status == "verified" else "#f59e0b" if status == "watch" else "#dc2626"
    label = escape(str(badge.get("label") or "dpone unknown"))
    return "\n".join(
        [
            '<svg xmlns="http://www.w3.org/2000/svg" width="640" height="160" viewBox="0 0 640 160" role="img">',
            '<rect width="640" height="160" rx="8" fill="#f8fafc"/>',
            f'<rect x="24" y="24" width="592" height="112" rx="8" fill="{color}"/>',
            f'<text x="48" y="72" font-size="30" font-weight="700" fill="#ffffff">{label}</text>',
            f'<text x="48" y="108" font-size="18" fill="#ecfeff">Quality: {score} / 100 · Trust Center Snapshot</text>',
            "</svg>\n",
        ]
    )


def _controls(payload: dict[str, Any], dpone: dict[str, Any]) -> list[dict[str, Any]]:
    risk = dpone.get("architecture_risk") or {}
    return [
        _control(
            "maintainability",
            "Industrial Maintainability",
            dpone.get("industrial_maintainability"),
            "SOLID/Clean OOP, module size, coupling, cohesion and freshness.",
        ),
        _matrix_control(payload, "governance_compliance", "Governance & Compliance"),
        _matrix_control(payload, "security_supply_chain", "Security & Supply Chain"),
        _matrix_control(payload, "operational_reliability", "Operational Reliability"),
        _matrix_control(payload, "operability_tco", "TCO & Operability"),
        _control(
            "coverage_confidence",
            "Coverage Confidence",
            dpone.get("coverage_confidence"),
            "Static test footprint plus CI/coverage configuration evidence.",
        ),
        {
            "slug": "architecture_risk",
            "label": "Architecture Risk",
            "score": max(0, 100 - _as_int(risk.get("score"))),
            "band": risk.get("level", "n/a"),
            "evidence": "Lower risk score means fewer oversized modules, fan-out hotspots and cohesion problems.",
        },
    ]


def _matrix_control(payload: dict[str, Any], key: str, label: str) -> dict[str, Any]:
    return _control(
        key, label, ((payload.get(key) or {}).get("summary") or {}).get("dpone"), f"{label} benchmark posture."
    )


def _control(slug: str, label: str, source: dict[str, Any] | None, evidence: str) -> dict[str, Any]:
    source = source or {}
    return {
        "slug": slug,
        "label": label,
        "score": _as_int(source.get("score")),
        "band": source.get("band", "n/a"),
        "evidence": evidence,
    }


def _status(score: int, gates: dict[str, Any], freshness: dict[str, Any]) -> str:
    if gates.get("status") != "passed" or score < 70:
        return "blocked"
    if score < 85 or freshness.get("stale", 0) or freshness.get("unavailable", 0):
        return "watch"
    return "verified"


def _find_project(payload: dict[str, Any], slug: str) -> dict[str, Any]:
    for project in payload.get("projects", []):
        if ((project.get("spec") or {}).get("slug")) == slug:
            return project
    return {}


def _as_int(value: Any) -> int:
    try:
        return int(round(float(value)))
    except (TypeError, ValueError):
        return 0


def _write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
